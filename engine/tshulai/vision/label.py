"""AI 生成內容標記。一定寫 EXIF（ImageDescription、Software）；有裝 c2pa-python 且設定了憑證就再加 C2PA。

C2PA 動作類型：合照是「用 AI 編輯過的真實照片」(compositeWithTrainedAlgorithmicMedia)，
整張生成的是 trainedAlgorithmicMedia。時間戳伺服器預設關（資料留在家裡），可在設定打開。
"""

from __future__ import annotations

import io
import logging
from pathlib import Path

from PIL import Image

log = logging.getLogger(__name__)
IPTC = "http://cv.iptc.org/newscodes/digitalsourcetype/"


def mark_ai_image(jpeg: bytes, *, composite: bool, title: str = "厝內合照",
                  cert_pem: Path | None = None, key_pem: Path | None = None, tsa_url: str | None = None) -> bytes:
    im = Image.open(io.BytesIO(jpeg))
    exif = im.getexif()
    exif[0x010E] = "AI composite: a family member was added by tshu-lai" if composite else "AI generated by tshu-lai"
    exif[0x0131] = "tshu-lai"
    out = io.BytesIO()
    im.convert("RGB").save(out, "JPEG", quality=92, exif=exif)
    data = out.getvalue()
    if not (cert_pem and key_pem):
        return data
    try:
        import c2pa
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import ec
    except ImportError:
        log.warning("沒裝 c2pa-python，只寫了 EXIF 標記")
        return data
    key = serialization.load_pem_private_key(key_pem.read_bytes(), password=None)

    def sign_es256(payload: bytes) -> bytes:
        return key.sign(payload, ec.ECDSA(hashes.SHA256()))

    manifest = {
        "claim_generator_info": [{"name": "tshu-lai", "version": "0.1"}], "format": "image/jpeg", "title": title,
        "assertions": [{"label": "c2pa.actions", "data": {"actions": [{
            "action": "c2pa.edited" if composite else "c2pa.created",
            "digitalSourceType": IPTC + ("compositeWithTrainedAlgorithmicMedia" if composite else "trainedAlgorithmicMedia"),
        }]}}],
    }
    src, dst = io.BytesIO(data), io.BytesIO()
    with c2pa.Context() as ctx, c2pa.Signer.from_callback(sign_es256, c2pa.C2paSigningAlg.ES256,
                                                          cert_pem.read_text(), tsa_url) as signer, c2pa.Builder(manifest, ctx) as b:
        b.sign("image/jpeg", src, dst, signer)
    return dst.getvalue()
